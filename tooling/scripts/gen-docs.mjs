// Generates the docs indexes from the file system. Run: node scripts/gen-docs.mjs
//  - content/docs/index.generated.ts     name -> ComponentDoc (content/docs/<name>.ts)
//  - components/docs/examples.generated.tsx  "<name>/<id>" -> lazy example (apps/docs/registry/examples/<name>/<id>.tsx)
//    Examples render client-only (ssr: false): many use today's date, locale or window size.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const ident = (s) => "d_" + s.replace(/[^a-zA-Z0-9]/g, "_")

const contentDir = path.join(root, "apps/docs/content/docs")
const docs = fs.readdirSync(contentDir).filter((f) => f.endsWith(".ts") && !f.endsWith(".generated.ts")).map((f) => f.slice(0, -3)).sort()
fs.writeFileSync(
  path.join(contentDir, "index.generated.ts"),
  `// Generated by scripts/gen-docs.mjs. Do not edit.\nimport type { ComponentDoc } from "@/lib/doc-types"\n\n` +
    docs.map((n) => `import ${ident(n)} from "./${n}"`).join("\n") +
    `\n\nexport const docsContent: Record<string, ComponentDoc> = {\n` +
    docs.map((n) => `  "${n}": ${ident(n)},`).join("\n") +
    `\n}\n`
)

const exDir = path.join(root, "apps/docs/registry/examples")
const keys = []
for (const d of fs.readdirSync(exDir, { withFileTypes: true })) {
  if (!d.isDirectory()) continue
  for (const f of fs.readdirSync(path.join(exDir, d.name)).sort()) if (f.endsWith(".tsx")) keys.push(`${d.name}/${f.slice(0, -4)}`)
}
keys.sort()
fs.writeFileSync(
  path.join(root, "apps/docs/components/docs/examples.generated.tsx"),
  `// Generated by scripts/gen-docs.mjs. Do not edit.\n"use client"\n\nimport type * as React from "react"\nimport dynamic from "next/dynamic"\n\nexport const examples: Record<string, React.ComponentType> = {\n` +
    keys.map((k) => `  "${k}": dynamic(() => import("@/registry/examples/${k}"), { ssr: false }),`).join("\n") +
    `\n}\n`
)
console.log(`docs: ${docs.length} content files, ${keys.length} examples`)

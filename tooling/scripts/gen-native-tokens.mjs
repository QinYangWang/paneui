// Portable colours are generated from the registry theme consumed by the Web components.
import { parse, clamp01 } from "./color.mjs"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const manifest = JSON.parse(fs.readFileSync(path.join(root, "packages/registry/registry.json"), "utf8"))
const { cssVars } = manifest.items.find((item) => item.name === "theme")
const roles = ["background", "foreground", "card", "card-foreground", "muted", "muted-foreground", "primary", "primary-hover", "primary-active", "primary-foreground", "secondary", "secondary-foreground", "border", "input", "ring", "destructive", "destructive-foreground", "success", "warning"]
const camel = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())
const colors = Object.fromEntries(["light", "dark"].map((mode) => [mode, Object.fromEntries(roles.map((role) => {
  const value = cssVars[mode][role]
  const { r, g, b, a } = parse(value)
  const channels = a < 1 ? [r, g, b, a] : [r, g, b]
  const hex = "#" + channels.map((n) => Math.round(clamp01(n) * 255).toString(16).padStart(2, "0")).join("")
  return [camel(role), hex]
}))]))
const text = `// Generated by pnpm tokens:gen from the registry theme. Do not edit.\nexport const colors = ${JSON.stringify(colors, null, 2)} as const\n\nexport type ColorScheme = keyof typeof colors\nexport type ColorRole = keyof typeof colors.light\nexport type ThemeColors = Readonly<Record<ColorRole, string>>\n`
const output = path.join(root, "packages/tokens/src/colors.generated.ts")
if (fs.existsSync(output) && fs.readFileSync(output, "utf8") === text) console.log("Portable colours unchanged")
else { fs.writeFileSync(output, text); console.log("Generated portable light and dark colours") }

const paperCss = fs.readFileSync(path.join(root, "packages/tokens/styles/theme-paper.css"), "utf8")
const blocks = [...paperCss.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/([^{}]+)\{([^{}]+)\}/g)]
const paperVars = Object.fromEntries(["light", "dark"].map((mode) => {
  const values = {}
  for (const [, selector, body] of blocks) {
    if (selector.includes(".dark") !== (mode === "dark") || selector.includes('[data-accent="')) continue
    for (const [, name, value] of body.matchAll(/--([\w-]+):\s*([^;]+);/g)) values[name] = value.trim()
  }
  return [mode, values]
}))
function portable(value) {
  const { r, g, b, a } = parse(value)
  return "#" + (a < 1 ? [r, g, b, a] : [r, g, b]).map((n) => Math.round(clamp01(n) * 255).toString(16).padStart(2, "0")).join("")
}
const paperColors = Object.fromEntries(["light", "dark"].map((mode) => [mode,
  Object.fromEntries(roles.map((role) => [camel(role), portable(paperVars[mode][role])]))
]))
const baseRadius = parseFloat(paperVars.light.radius) * 16
const cap = 16
const paperRadius = Object.fromEntries(Object.entries({ sm: .5, md: .75, lg: 1, xl: 1.25, "2xl": 1.5, "3xl": 2 }).map(([key, factor]) => [key, Math.min(cap, baseRadius * factor)]))
// Native supports one drop shadow. Use the broadest layer; surfaces keep their own hairline.
function shadow(value) {
  const layers = [...value.matchAll(/(-?\d+)(?:px)? (-?\d+)(?:px)? (\d+)px(?: (-?\d+)px)? (oklch\([^)]+\))/g)]
  const layer = layers.at(-1)
  if (!layer) throw new Error(`Missing drop shadow: ${value}`)
  const [, x, y, blur, , color] = layer
  const { a } = parse(color)
  return { shadowColor: portable(color.replace(/\s*\/[^)]+/, "")), shadowOffset: { width: Number(x), height: Number(y) }, shadowOpacity: a, shadowRadius: Number(blur) / 2, elevation: Math.max(1, Math.round(Number(blur) / 8)) }
}
const paperShadows = Object.fromEntries(["light", "dark"].map((mode) => [mode, {
  raised: shadow(paperVars[mode]["shadow-default"]), surface: shadow(paperVars[mode]["shadow-lg"]), overlay: shadow(paperVars[mode]["shadow-xl"]),
}]))
const paper = { colors: paperColors, radius: paperRadius, controlRadius: Math.min(cap, parseFloat(paperVars.light["control-radius"]) * 16), headingFont: paperVars.light["heading-font"], shadows: paperShadows }
fs.writeFileSync(path.join(root, "packages/tokens/src/paper.generated.ts"), `// Generated by pnpm tokens:gen from theme-paper.css. Do not edit.\nexport const paper = ${JSON.stringify(paper, null, 2)} as const\n`)

// Portable colours are generated from the registry theme consumed by the Web components.
import { parse, clamp01 } from "./color.mjs"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const manifest = JSON.parse(fs.readFileSync(path.join(root, "packages/registry/registry.json"), "utf8"))
const { cssVars } = manifest.items.find((item) => item.name === "theme")
const roles = ["background", "foreground", "card", "card-foreground", "muted", "muted-foreground", "primary", "primary-hover", "primary-active", "primary-foreground", "secondary", "secondary-foreground", "border", "input", "ring", "destructive", "destructive-foreground", "success", "warning"]
const camel = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())
const colors = Object.fromEntries(["light", "dark"].map((mode) => [mode, Object.fromEntries(roles.map((role) => {
  const value = cssVars[mode][role]
  const { r, g, b, a } = parse(value)
  const channels = a < 1 ? [r, g, b, a] : [r, g, b]
  const hex = "#" + channels.map((n) => Math.round(clamp01(n) * 255).toString(16).padStart(2, "0")).join("")
  return [camel(role), hex]
}))]))
const text = `// Generated by pnpm tokens:gen from the registry theme. Do not edit.\nexport const colors = ${JSON.stringify(colors, null, 2)} as const\n\nexport type ColorScheme = keyof typeof colors\nexport type ColorRole = keyof typeof colors.light\nexport type ThemeColors = Readonly<Record<ColorRole, string>>\n`
const output = path.join(root, "packages/tokens/src/colors.generated.ts")
if (fs.existsSync(output) && fs.readFileSync(output, "utf8") === text) console.log("Portable colours unchanged")
else { fs.writeFileSync(output, text); console.log("Generated portable light and dark colours") }

import { readdir, readFile, writeFile } from "node:fs/promises";
const root = new URL("../../apps/native/docs/examples/", import.meta.url);
const sources = {};
for (const slug of await readdir(root)) {
  for (const file of await readdir(new URL(`${slug}/`, root))) {
    if (!file.endsWith(".tsx")) continue;
    const id = file.replace(/\.tsx$/, "");
    sources[`${slug}/${id}`] = await readFile(
      new URL(`${slug}/${file}`, root),
      "utf8",
    );
  }
}
await writeFile(
  new URL("../../apps/native/docs/sources.generated.ts", import.meta.url),
  `// Generated by tooling/scripts/native-example-sources.mjs.\nexport const sources: Record<string, string> = ${JSON.stringify(sources, null, 2)}\n`,
);

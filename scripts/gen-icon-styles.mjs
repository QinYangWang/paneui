#!/usr/bin/env node
/**
 * Generate the outline icon set from the puffy one (`pnpm icons:gen`, also run by
 * `pnpm registry:build`).
 *
 *   registry/base-nova/icons/puffy/icons.tsx     source of truth (puffy, hand drawn)
 *   scripts/icon-outline-overrides.mjs           per-icon outline redraws
 *   registry/base-nova/icons/outline/icons.tsx   GENERATED, never edit by hand
 *
 * How: the puffy file is copied export by export. The `puff` primitive (filled, 1.5
 * round-join stroke) is redefined as an outline stroke (no fill, 1.6 stroke, round caps
 * and joins, the same as `line`), so every filled shape becomes its own contour on the
 * same geometry. Icons listed in the override map get their body replaced by the
 * override's markup (knockouts that would double up, holes that should become lines,
 * shapes that need more room inside). Overrides may use `solid`, the old filled puff,
 * for tiny dots that should stay filled.
 *
 * `node scripts/gen-icon-styles.mjs --check` exits 1 if the generated file is stale,
 * or if an override names an icon the puffy set does not export.
 */
import fs from "node:fs"
import path from "node:path"

import { outlineOverrides } from "./icon-outline-overrides.mjs"

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..")
const srcPath = path.join(root, "registry/base-nova/icons/puffy/icons.tsx")
const outPath = path.join(root, "registry/base-nova/icons/outline/icons.tsx")
const check = process.argv.includes("--check")

const src = fs.readFileSync(srcPath, "utf8")

const PUFF = /^\/\/ Trace every filled shape with this\..*\nconst puff = \{[^\n]*\} as const;\n/m
if (!PUFF.test(src)) throw new Error("gen-icon-styles: could not find the `puff` definition in the puffy icons file")

const HEADER = /^\/\*[\s\S]*?\*\/\n/
if (!HEADER.test(src)) throw new Error("gen-icon-styles: could not find the header comment in the puffy icons file")

const EXPORT = /^export const (\w+Icon) = \(p: IconProps\) => \(\n  <Icon \{\.\.\.p\}>\n([\s\S]*?)\n  <\/Icon>\n\);$/gm
const names = [...src.matchAll(EXPORT)].map((m) => m[1])
const declared = src.match(/^export const \w+Icon\b/gm)?.length ?? 0
if (names.length !== declared)
  throw new Error(`gen-icon-styles: ${declared} icon exports but only ${names.length} match the expected shape`)

const unknown = Object.keys(outlineOverrides).filter((n) => !names.includes(n))
if (unknown.length) {
  console.error(`gen-icon-styles: overrides for icons that do not exist: ${unknown.join(", ")}`)
  process.exit(1)
}

const header = `/*
 * taimatsu/ui icon set, outline style. GENERATED by scripts/gen-icon-styles.mjs from
 * registry/base-nova/icons/puffy/icons.tsx and scripts/icon-outline-overrides.mjs. Do not edit by hand.
 *
 * Same 18x18 grid, names and props as the puffy set: filled shapes are drawn as
 * 1.6px round outlines, open glyphs keep their 1.6px stroke, tiny dots stay solid.
 * Install it over the puffy set with
 *   pnpm dlx shadcn@latest add https://qinyangwang.github.io/ui/r/icons-outline.json --overwrite
 * and switch back with the same command and icons.json.
 */
`

const outlinePrimitives = `// Outline style: every shape that is filled in the puffy set is traced as a round contour, the same
// width as line (1.6, set on the <svg>).
const puff = { fill: "none", stroke: "currentColor", strokeLinecap: "round", strokeLinejoin: "round" } as const;

// Tiny dots stay filled so they keep their weight.
const solid = { stroke: "currentColor", strokeWidth: 1.5, strokeLinejoin: "round" } as const;
`

const indent = (body) =>
  body
    .trim()
    .split("\n")
    .map((l) => `    ${l.trim()}`)
    .join("\n")

let out = src.replace(HEADER, header).replace(PUFF, outlinePrimitives)
out = out.replace(EXPORT, (whole, name) => {
  // Filled nav variants (the active state) keep the puffy fill: `solid` is the filled puff.
  if (name.endsWith("FilledIcon")) return whole.replace(/\{\.\.\.puff\}/g, "{...solid}")
  const o = outlineOverrides[name]
  if (o === undefined) return whole
  return `export const ${name} = (p: IconProps) => (\n  <Icon {...p}>\n${indent(o)}\n  </Icon>\n);`
})
if (!/\{\.\.\.solid\}/.test(out)) out = out.replace(/\n\/\/ Tiny dots stay filled[^\n]*\nconst solid = [^\n]*\n/, "\n")

const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : ""
if (check) {
  if (current !== out) {
    console.error("gen-icon-styles: registry/base-nova/icons/outline/icons.tsx is stale, run `pnpm icons:gen`")
    process.exit(1)
  }
  console.log(`gen-icon-styles: outline set up to date (${names.length} icons, ${Object.keys(outlineOverrides).length} overrides)`)
} else {
  fs.mkdirSync(path.dirname(outPath), { recursive: true })
  if (current !== out) fs.writeFileSync(outPath, out)
  console.log(
    `gen-icon-styles: ${names.length} icons -> ${path.relative(root, outPath)} (${Object.keys(outlineOverrides).length} overrides)${current === out ? ", unchanged" : ""}`
  )
}

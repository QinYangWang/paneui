const OG_IMAGE_WIDTH = 1200
const OG_IMAGE_HEIGHT = 630
/** The `size` export of an `opengraph-image` or `twitter-image` route. */
const ogImageSize = { width: OG_IMAGE_WIDTH, height: OG_IMAGE_HEIGHT }
/** The `contentType` export of the route. */
const ogImageContentType = "image/png"

/** The colours for an accent and mode, with any overrides on top. */
function ogImageColors(accent: OgImageAccent = "blue", mode: OgImageMode = "light", overrides?: Partial<OgImageColors>): OgImageColors {
  const base = (OG_IMAGE_TOKENS[accent] ?? OG_IMAGE_TOKENS.blue)[mode === "dark" ? "dark" : "light"]
  return overrides ? { ...base, ...overrides } : base
}

/** `color` at `alpha` over `base`, as opaque hex: the renderer's gradients and fills stay sRGB. */
function mixHex(color: string, base: string, alpha: number) {
  const rgb = (h: string) => {
    const x = h.replace("#", "")
    const full = x.length === 3 ? [...x].map((c) => c + c).join("") : x.slice(0, 6)
    return [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16))
  }
  const a = rgb(color)
  const b = rgb(base)
  return `#${a.map((v, i) => Math.round(v * alpha + b[i] * (1 - alpha)).toString(16).padStart(2, "0")).join("")}`
}

/* Seed hash shared with ShaderBackground, so a seed gives the same colours everywhere. */
function hashSeed(seed: string) {
  let h = 0x811c9dc5
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return h >>> 0
}
function mix(h: number) {
  h ^= h >>> 16
  h = Math.imul(h, 0x85ebca6b)
  h ^= h >>> 13
  h = Math.imul(h, 0xc2b2ae35)
  h ^= h >>> 16
  return h >>> 0
}
function hslHex(h: number, s: number, l: number) {
  const a = (s / 100) * Math.min(l / 100, 1 - l / 100)
  const f = (n: number) => {
    const k = (n + h / 30) % 12
    const v = l / 100 - a * Math.max(-1, Math.min(k - 3, 9 - k, 1))
    return Math.round(v * 255).toString(16).padStart(2, "0")
  }
  return `#${f(0)}${f(8)}${f(4)}`
}
const SCHEMES = [
  [0, 30, 60, 200],
  [0, 150, 180, 330],
  [0, 40, 180, 220],
] as const
const LIGHTS = [58, 72, 86, 66]

/** The seeded palette ShaderBackground uses for `colors="random"`, as hex. */
function ogPalette(seed: string, count = 4): string[] {
  const h = mix(hashSeed(seed))
  const hue = h % 360
  const scheme = SCHEMES[(h >>> 9) % SCHEMES.length]
  const sat = 68 + ((h >>> 12) % 20)
  return Array.from({ length: count }, (_, i) => hslHex((hue + scheme[i % scheme.length] + Math.floor(i / scheme.length) * 15) % 360, Math.max(40, sat - i * 6), LIGHTS[i % LIGHTS.length]))
}

/**
 * A still frame of the mesh-gradient shader: soft colour fields over the first colour. The PNG
 * renderer has no WebGL, so blobs are radial gradients placed by the seed.
 */
function meshLayers(colors: string[], seed: string) {
  const h = mix(hashSeed(seed))
  return colors
    .slice(1)
    .map((color, i) => {
      const r = mix(h ^ Math.imul(i + 1, 0x9e3779b9))
      const x = r % 101
      const y = (r >>> 8) % 101
      const size = 55 + ((r >>> 16) % 30)
      return `radial-gradient(circle at ${x}% ${y}%, ${color} 0%, ${color}00 ${size}%)`
    })
    .reverse()
}

/** Resolves a `palette` prop to hex colours: given, seeded random, or the accent ramp. */
function resolvePalette(palette: string[] | "random" | undefined, seed: string, c: OgImageColors) {
  if (Array.isArray(palette) && palette.length > 0) return palette
  if (palette === "random") return ogPalette(seed)
  return [c.background, c.primary, mixHex(c.primary, c.background, 0.45), mixHex(c.primary, c.background, 0.2)]
}

const WIDE = /[\u1100-\u115f\u2e80-\ua4cf\uac00-\ud7a3\uf900-\ufaff\ufe30-\ufe4f\uff00-\uff60\uffe0-\uffe6]/u

/** Title size in px: shorter titles get bigger type. CJK and full-width characters count double. */
function ogImageTitleSize(title: string): number {
  let width = 0
  for (const ch of title) width += WIDE.test(ch) ? 2 : 1
  if (width <= 24) return 80
  if (width <= 44) return 68
  if (width <= 72) return 56
  return 46
}

type OgImageProps = {
  title: string
  description?: string
  /** Shown at the top, beside `logo`. */
  siteName: string
  /** Shown at the top right, e.g. the page's host and path. */
  url?: string
  author?: string
  /** Round image beside the author. A URL or data URI (PNG, JPEG or SVG). */
  avatar?: string
  /** Square image beside the site name. A URL or data URI (PNG, JPEG or SVG). */
  logo?: string
  /** Shown as given, after the author. Format it in the page's language. */
  date?: string
  /** The first three are shown. */
  tags?: string[]
  accent?: OgImageAccent
  mode?: OgImageMode
  /** Shader colours as hex, or `"random"`. Defaults to the accent. */
  palette?: string[] | "random"
  /** Picks the random palette and the shader's layout. Defaults to `title`. */
  seed?: string
  /** A background image URL or data URI (PNG or JPEG) instead of the shader, under a wash that keeps the text readable. */
  image?: string
  /** Overrides for single roles, on top of the accent and mode. */
  colors?: Partial<OgImageColors>
  /** Family name the fonts were registered under. Without it the renderer's first font is used. */
  fontFamily?: string
  /** Styles merged onto the root, for a renderer quirk or a background image. */
  style?: React.CSSProperties
}

const PAD_X = 80
const PAD_Y = 72
const INNER = OG_IMAGE_WIDTH - PAD_X * 2
const HEADER = 52
const FOOTER = 52
function OgImage({
  title,
  description,
  siteName,
  url,
  author,
  avatar,
  logo,
  date,
  tags = [],
  accent = "blue",
  mode = "light",
  palette,
  seed,
  image,
  colors,
  fontFamily,
  style,
}: OgImageProps) {
  const c = ogImageColors(accent, mode, colors)
  const size = ogImageTitleSize(title)
  const titleLines = size >= 68 ? 2 : 3
  const descLines = 2
  const shownTags = tags.filter(Boolean).slice(0, 3)
  const meta = [author, date].filter(Boolean).join(" · ")
  const footer = Boolean(meta || avatar || shownTags.length)
  // Text boxes don't shrink inside flex columns, so the body gets the height that is left.
  const body = OG_IMAGE_HEIGHT - PAD_Y * 2 - HEADER - (footer ? FOOTER + 24 : 0)
  // room below the last line for descenders (CJK fonts draw about 1.36em tall)
  const titleSlack = Math.ceil(size * 0.15)
  const descSlack = Math.ceil(30 * 0.15)
  const fields = image ? null : resolvePalette(palette, seed ?? title, c)
  const full = { position: "absolute" as const, left: 0, top: 0, width: OG_IMAGE_WIDTH, height: OG_IMAGE_HEIGHT, display: "flex" }

  return (
    <div
      data-slot="og-image"
      style={{
        width: OG_IMAGE_WIDTH,
        height: OG_IMAGE_HEIGHT,
        display: "flex",
        flexDirection: "column",
        position: "relative",
        boxSizing: "border-box",
        padding: `${PAD_Y}px ${PAD_X}px`,
        overflow: "hidden",
        backgroundColor: c.background,
        color: c.foreground,
        fontFamily,
        ...style,
      }}
    >
      {image && <img src={image} width={OG_IMAGE_WIDTH} height={OG_IMAGE_HEIGHT} alt="" style={{ ...full, objectFit: "cover" }} />}
      {fields && <div style={{ ...full, backgroundColor: fields[0], backgroundImage: meshLayers(fields, seed ?? title).join(", ") }} />}
      {/* a wash from the text side, so titles stay readable over any picture or palette */}
      <div
        style={{
          ...full,
          backgroundImage: `linear-gradient(to top right, ${c.background}f2 0%, ${c.background}cc 45%, ${c.background}40 100%)`,
        }}
      />

      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 24, height: HEADER, width: INNER, position: "relative" }}>
        <div style={{ display: "flex", alignItems: "center", gap: 18 }}>
          {logo && <img src={logo} width={52} height={52} alt="" style={{ width: 52, height: 52, borderRadius: 12, objectFit: "cover" }} />}
          <div style={{ display: "flex", fontSize: 30, fontWeight: 700, lineHeight: 1.2, letterSpacing: -0.5, color: c.foreground }}>{siteName}</div>
        </div>
        {url && <div style={{ display: "flex", fontSize: 26, lineHeight: 1.2, color: c.mutedForeground }}>{url}</div>}
      </div>

      <div
        style={{
          display: "flex",
          flexDirection: "column",
          justifyContent: "flex-end",
          gap: 20,
          width: INNER,
          height: body,
          overflow: "hidden",
          position: "relative",
        }}
      >
        <div
          style={{
            display: "block",
            width: INNER - 80,
            // The glyphs reach past the line box, so the box gets room below the last line
            // for descenders and a matching negative margin keeps the layout unchanged.
            boxSizing: "border-box",
            maxHeight: Math.ceil(size * 1.15 * titleLines) + titleSlack,
            paddingBottom: titleSlack,
            marginBottom: -titleSlack,
            overflow: "hidden",
            fontSize: size,
            fontWeight: 700,
            lineHeight: 1.15,
            letterSpacing: size >= 56 ? -2 : -1,
            lineClamp: titleLines,
          }}
        >
          {title}
        </div>
        {description && (
          <div
            style={{
              display: "block",
              width: INNER - 160,
              boxSizing: "border-box",
              maxHeight: Math.ceil(30 * 1.4 * descLines) + descSlack,
              paddingBottom: descSlack,
              marginBottom: -descSlack,
              overflow: "hidden",
              fontSize: 30,
              lineHeight: 1.4,
              color: c.mutedForeground,
              lineClamp: descLines,
            }}
          >
            {description}
          </div>
        )}
      </div>

      {footer && (
        <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 24, width: INNER, height: FOOTER, marginTop: 24, position: "relative" }}>
          <div style={{ display: "flex", alignItems: "center", gap: 14 }}>
            {avatar && <img src={avatar} width={44} height={44} alt="" style={{ width: 44, height: 44, borderRadius: 22, objectFit: "cover" }} />}
            {meta && <div style={{ display: "flex", fontSize: 26, lineHeight: 1.2, color: c.mutedForeground }}>{meta}</div>}
          </div>
          {shownTags.length > 0 && (
            <div style={{ display: "flex", alignItems: "center", gap: 10 }}>
              {shownTags.map((tag) => (
                <div
                  key={tag}
                  style={{
                    display: "flex",
                    alignItems: "center",
                    height: 44,
                    padding: "0 18px",
                    borderRadius: 22,
                    border: `1.5px solid ${c.primaryBorder}`,
                    fontSize: 22,
                    lineHeight: 1,
                    color: c.primary,
                    backgroundColor: c.primarySubtle,
                  }}
                >
                  {tag}
                </div>
              ))}
            </div>
          )}
        </div>
      )}
    </div>
  )
}

